"""CI-only Lean C -> Emscripten feasibility gate; no runtime port patches.

Run from the repository root on Linux after the workflow's proof step.
Every subprocess is bounded by the job's 40-minute timeout. Failure preserves
its stage and log; it does not trigger another toolchain or runtime approach.
"""
import concurrent.futures
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import time
from canonical_evidence import collect_manifest, archive_pass, clean_archived_build, compare_passes

ROOT = Path.cwd()
OUTPUT = ROOT / ".data/wasm-gate"
WORK = ROOT / ".data/wasm-build"
CANONICAL = WORK / "canonical"
SOURCES = ROOT / "qa/wasm-feasibility"
PINS = {
    "lean": "6caaee842e9495688c1567e78c0e68dbb96942aa",
    "emsdk": "a896e3d066448b3530dbcaa48869fafefd738f57",
    "emscripten": "3.1.44",
    "libuv": "e9f29cb984231524e3931aa0ae2c5dae1a32884e",
    "batteries": "f5d04a9c4973d401c8c92500711518f7c656f034",
    "playwright": "1.51.1",
}
receipt = {"pins": PINS, "stage": "setup", "passed": False,
           "proof": "see separate axioms.log and axiom-audit.json", "browser": "not reached",
           "repeatability": False, "runtime_gate_passed": False,
           "overall_gate_passed": False, "hosting_gate": "pending"}


def run(arguments, *, cwd=ROOT, env=None, capture=False):
    """Run explicit arguments without a shell; show commands but no environment."""
    print("+", " ".join(map(str, arguments)), flush=True)
    # Keep stderr in the CI log even when collecting a command's stdout.
    result = subprocess.run(list(map(str, arguments)), cwd=cwd, env=env,
                            check=True, text=True,
                            stdout=subprocess.PIPE if capture else None)
    return result.stdout.strip() if capture else None


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def checkout(url, revision, destination):
    run(["git", "init", destination])
    run(["git", "fetch", "--depth=1", url, revision], cwd=destination)
    run(["git", "checkout", "--detach", "FETCH_HEAD"], cwd=destination)
    assert run(["git", "rev-parse", "HEAD"], cwd=destination, capture=True) == revision


def save_receipt():
    receipt["files"] = {
        str(path.relative_to(ROOT)): digest(path)
        for path in sorted(SOURCES.glob("*")) if path.is_file()
    }
    receipt["dependency_lock_sha256"] = digest(ROOT / "proofs/lake-manifest.json")
    (OUTPUT / "receipt.json").write_text(json.dumps(receipt, indent=2) + "\n")


def generate_c(environment, native_lean, index):
    """Regenerate each imported module with the pinned native compiler.

    The shipped bootstrap stage0 C is deliberately not reused: it need not
    have been generated by 4.19. Lean --deps supplies the actual import graph.
    Only Init, Batteries and this checker are allowed in the runtime closure.
    Mathlib and Lean's elaborator/compiler stay in the proof/build environment.
    """
    generated = CANONICAL / "generated"
    generated.mkdir()
    prefix = Path(run([native_lean, "--print-prefix"], env=environment, capture=True))
    roots = [ROOT / "proofs", ROOT / "proofs/.lake/packages/batteries", prefix / "src/lean"]
    pending = ["SmokeChecker"]
    modules = {}
    while pending:
        module = pending.pop()
        if module in modules:
            continue
        assert module == "SmokeChecker" or module == "Init" or module.startswith(("Init.", "Batteries.")), module
        relative = Path(*module.split(".")).with_suffix(".lean")
        source_root = next(root for root in roots if (root / relative).is_file())
        source = source_root / relative
        modules[module] = (source_root, source)
        dependencies = run([native_lean, "--deps", source], cwd=ROOT / "proofs",
                           env=environment, capture=True)
        for line in dependencies.splitlines():
            dependency = line.strip().replace("\\", "/")
            assert dependency.endswith(".olean"), dependency
            relative_dependency = dependency.rsplit("/lib/lean/", 1)[-1]
            pending.append(relative_dependency[:-6].replace("/", "."))

    def compile_module(item):
        name, (source_root, source) = item
        target = generated / (name + ".c")
        run([native_lean, "-R", source_root, "-c", target, source],
            cwd=ROOT / "proofs", env=environment)
        return name, {"source_sha256": digest(source), "c_sha256": digest(target)}

    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
        receipt[f"generated_modules_{index}"] = dict(pool.map(compile_module, sorted(modules.items())))
    assert digest(generated / "SmokeChecker.c") == digest(OUTPUT / "SmokeChecker.c")
    return generated


def build_artifact(index, environment, generated):
    """Fresh products at the identical absolute paths on both passes."""
    build = CANONICAL
    runtime = build / "runtime"
    run(["emcmake", "cmake", "-S", WORK / "lean/src", "-B", runtime,
         "-DSTAGE=1", "-DCMAKE_BUILD_TYPE=Release", "-DUSE_GMP=OFF",
         "-DUSE_MIMALLOC=OFF", "-DMMAP=OFF", "-DUSE_LAKE=OFF", "-DCCACHE=OFF",
         "-DPREV_STAGE=" + str(Path(receipt["native_lean"]).parent.parent)], env=environment)
    run(["cmake", "--build", runtime, "--target", "leanrt", "-j2"], env=environment)
    libuv = runtime / "libuv/src/libuv"
    assert run(["git", "rev-parse", "HEAD"], cwd=libuv, capture=True) == PINS["libuv"]
    # The only patched external source is the patch embedded in pinned Lean.
    receipt[f"libuv_patch_{index}"] = run(["git", "diff"], cwd=libuv, capture=True)
    objects = build / "objects"
    objects.mkdir()
    flags = ["-O2", "-flto", "-pthread", "-fwasm-exceptions", "-I", runtime / "include",
             "-I", WORK / "lean/src/include"]

    def compile_c(source):
        target = objects / (source.stem + ".o")
        run(["emcc", *flags, "-c", source, "-o", target], env=environment)
        return target

    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
        compiled = list(pool.map(compile_c, sorted(generated.glob("*.c"))))
    wrapper = compile_c(SOURCES / "abi.c")
    archive = build / "checker-core.a"
    run(["emar", "rcs", archive, *compiled], env=environment)
    assets = build / "assets"
    assets.mkdir()
    # The single authorized link experiment resolves this libc symbol before LTO.
    run(["em++", *flags, "-Wl,-u,ntohs", "--no-entry", wrapper, "-Wl,--start-group", archive,
         runtime / "lib/lean/libleanrt.a", libuv / "libuv.a", "-Wl,--end-group",
         "-sMODULARIZE=1", "-sEXPORT_ES6=1", "-sEXPORT_NAME=createChecker",
         "-sENVIRONMENT=web,worker", "-sALLOW_MEMORY_GROWTH=1",
         "-sINITIAL_MEMORY=33554432", "-sMAXIMUM_MEMORY=134217728",
         "-sPTHREAD_POOL_SIZE=0", "-sERROR_ON_UNDEFINED_SYMBOLS=1",
         "-sEXPORTED_FUNCTIONS=['_checker_init','_checker_check','_input_ptr','_input_capacity']",
         "--emit-symbol-map", "-o", assets / "checker.mjs"], env=environment)
    return assets


def main():
    assert sys.platform == "linux", "This gate may run only in Linux CI."
    assert os.environ.get("GITHUB_ACTIONS") == "true", "CI-only gate."
    WORK.mkdir(parents=True)
    receipt["commit"] = run(["git", "rev-parse", "HEAD"], capture=True)
    receipt["runner"] = {key: os.environ.get(key) for key in ("ImageOS", "ImageVersion", "RUNNER_ARCH")}
    receipt["host_tools"] = {name: run([name, "--version"], capture=True).splitlines()[0]
                             for name in ("cmake", "python3", "node", "npm", "git")}
    for name, url in (("lean", "https://github.com/leanprover/lean4.git"),
                      ("emsdk", "https://github.com/emscripten-core/emsdk.git")):
        checkout(url, PINS[name], WORK / name)
    run(["./emsdk", "install", PINS["emscripten"]], cwd=WORK / "emsdk")
    run(["./emsdk", "activate", PINS["emscripten"]], cwd=WORK / "emsdk")
    # Read only the path settings required for tools, never log CI secrets.
    settings = run(["bash", "-c", 'source .data/wasm-build/emsdk/emsdk_env.sh >/dev/null 2>&1; '
                    'cd proofs; lake env python3 -c '
                    '\'import json,os; print(json.dumps({k:os.environ[k] for k in '
                    '["PATH","LEAN_PATH","EMSDK","EM_CONFIG","EMSDK_NODE"] if k in os.environ}))\''], capture=True)
    environment = {**os.environ, **json.loads(settings), "SOURCE_DATE_EPOCH": "1746057600"}
    # Emscripten treats even an empty EM_CONFIG as an explicit filename. Use
    # the SDK's generated config, never an empty placeholder for an unset key.
    environment["EM_CONFIG"] = str(WORK / "emsdk/.emscripten")
    receipt["emscripten_config_sha256"] = digest(Path(environment["EM_CONFIG"]))
    environment["LEAN_PATH"] = str(ROOT / "proofs") + ":" + environment["LEAN_PATH"]
    native_lean = shutil.which("lean", path=environment["PATH"])
    # Resolve elan's selected toolchain, not the dispatcher's executable hash.
    native_lean = run(["elan", "which", "lean"], cwd=ROOT / "proofs", env=environment, capture=True)
    receipt["native_lean"] = native_lean
    receipt["native_lean_sha256"] = digest(Path(native_lean))
    receipt["lean_version"] = run([native_lean, "--version"], env=environment, capture=True)
    assert "4.19.0" in receipt["lean_version"]
    receipt["emcc_version"] = run(["emcc", "--version"], env=environment, capture=True)
    assert "3.1.44" in receipt["emcc_version"]
    receipt["emsdk_manifest_sha256"] = digest(WORK / "emsdk/emscripten-releases-tags.json")
    receipt["canonical_paths"] = {name: str(CANONICAL / name)
                                  for name in ("generated", "runtime", "runtime/include", "objects", "assets")}
    receipt["source_paths"] = {"lean": str(WORK / "lean"), "checker": str(ROOT / "proofs/SmokeChecker.lean"),
                               "batteries": str(ROOT / "proofs/.lake/packages/batteries")}
    receipt["source_date_epoch"] = environment["SOURCE_DATE_EPOCH"]
    receipt["toolchain_cache_policy"] = "Pinned installed SDK and its system-library cache are shared; every Lean/libuv/checker generated file, header, object, archive and final output is freshly built. No project object cache is reused."
    receipt["proof_audit_sha256"] = digest(OUTPUT / "axiom-audit.json")
    manifests = []
    for index in (1, 2):
        if index == 2:
            receipt["stage"] = "verify-archive-and-clean"
            save_receipt()
            receipt["cleanup"] = clean_archived_build(CANONICAL, ROOT, OUTPUT / "pass-1", manifests[0])
        CANONICAL.mkdir()
        receipt["stage"] = f"generate-import-closure-{index}"
        save_receipt()
        generated = generate_c(environment, native_lean, index)
        receipt["stage"] = f"artifact-build-{index}"
        save_receipt()
        assets = build_artifact(index, environment, generated)
        manifest = collect_manifest(ROOT, WORK, CANONICAL,
                                    receipt[f"generated_modules_{index}"])
        manifests.append(manifest)
        archive_pass(ROOT, OUTPUT / f"pass-{index}", manifest)
        receipt[f"manifest_{index}_sha256"] = digest(OUTPUT / f"pass-{index}/manifest.json")
        save_receipt()
    receipt["stage"] = "compare-clean-builds"
    receipt["comparison"] = compare_passes(*manifests)
    receipt["artifact_hashes"] = manifests[0]["layers"]["final_assets"]
    receipt["repeat_hashes"] = manifests[1]["layers"]["final_assets"]
    save_receipt()
    assert receipt["comparison"]["equal"], "Canonical build mismatch: " + str(receipt["comparison"]["first_differing_layer"])
    receipt["repeatability"] = True
    receipt["stage"] = "browser"
    browser = OUTPUT / "browser"
    browser.mkdir()
    run(["npm", "install", "--prefix", browser, "--ignore-scripts", "--save-exact",
         "playwright@" + PINS["playwright"]])
    run(["node", browser / "node_modules/playwright/cli.js", "install", "--with-deps", "chromium"])
    shutil.copy(SOURCES / "browser-test.mjs", browser / "browser-test.mjs")
    # Playwright uses the recorded CI host Node, not Emsdk's bundled Node 16.
    run(["node", browser / "browser-test.mjs", assets, SOURCES])
    shutil.copyfile(CANONICAL / "browser-results.json", OUTPUT / "browser-results.json")
    receipt["browser"] = json.loads((OUTPUT / "browser-results.json").read_text())
    receipt["browser_package_lock_sha256"] = digest(browser / "package-lock.json")
    # Browser dependencies are test-only and are excluded from the published evidence zip.
    shutil.rmtree(browser / "node_modules")
    receipt["passed"] = True
    receipt["runtime_gate_passed"] = True
    # Hosting isolation and portal integration are still separate, pending gates.
    receipt["stage"] = "complete"


if __name__ == "__main__":
    started = time.monotonic()
    try:
        main()
    except Exception as error:
        receipt["failure"] = str(error)
        raise
    finally:
        receipt["elapsed_seconds"] = time.monotonic() - started
        save_receipt()
