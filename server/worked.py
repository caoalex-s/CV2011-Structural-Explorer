def number(value):
    return str(sp.Rational(value))


def coefficients(expression):
    polynomial = sp.Poly(sp.expand(expression), X)
    if polynomial.degree() > 5:
        raise ValueError("The formal certificate supports polynomials up to degree five.")
    return [polynomial.nth(i) for i in range(6)]


def lean_number(value):
    value = sp.Rational(value)
    return f"({value.p} / {value.q} : Rat)"


def lean_poly(expression):
    return "[" + ", ".join(lean_number(v) for v in coefficients(expression)) + "]"


def math_expression(expression):
    """Presentation MathML is generated from our expressions, never user markup."""
    from sympy.printing.mathml import mathml
    return '<math xmlns="http://www.w3.org/1998/Math/MathML">' + mathml(sp.expand(expression), printer="presentation") + '</math>'


def equation(label, expression, unit="", label_latex=None):
    """Return the same exact expression as text, LaTeX, and legacy MathML."""
    labels = {
        "Σ applied Fx": r"\sum F_x^{\mathrm{applied}}",
        "F = Σ applied Fy": r"F=\sum F_y^{\mathrm{applied}}",
        "T = Σ applied moment about x = 0": r"T=\sum M_0^{\mathrm{applied}}",
        "Rᵣ = (aF − T)/(b − a)": r"R_{\mathrm r}=\frac{aF-T}{b-a}",
        "Rₗ = −F − Rᵣ": r"R_{\mathrm l}=-F-R_{\mathrm r}",
        "H = −Σ applied Fx": r"H=-\sum F_x^{\mathrm{applied}}",
        "C₁": r"C_1", "C₀": r"C_0", "θ": r"\theta",
        "θ(x)": r"\theta(x)", "θ(a)": r"\theta(a)",
        "Δθ": r"\Delta\theta", "t": r"t_{c/a}",
        "Virtual Rₗ": r"R_{\mathrm l}^{\mathrm{virtual}}",
        "Virtual Rᵣ": r"R_{\mathrm r}^{\mathrm{virtual}}",
        "v(xₛ)": r"v(x_s)",
    }
    if label_latex is None:
        if label in labels:
            label_latex = labels[label]
        elif label in {"q(x)", "N(x)", "V(x)", "M(x)", "B(x)", "v(x)", "m(x)", "N", "V", "M", "v"}:
            label_latex = label
        else:
            # These labels are generated by the application, not user markup.
            label_latex = r"\text{" + label + "}"
    expression = sp.expand(expression)
    return {
        "label": label, "labelLatex": label_latex,
        "latex": sp.latex(expression), "exact": str(expression), "unit": unit,
        "mathml": math_expression(expression),
    }


